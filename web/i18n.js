  var KEY = 'testhub.lang';
  var htmlLang = { zh: 'zh-CN', en: 'en' };

  function detect() {
    try {
      var saved = localStorage.getItem(KEY);
      if (saved === 'en' || saved === 'zh') return saved;
    } catch (e) { /* ignore */ }
    var nav = (typeof navigator !== 'undefined' && (navigator.language || '')).toLowerCase();
    return nav.indexOf('zh') === 0 ? 'zh' : 'en';
  }

  var lang = detect();

  function interpolate(s, vars) {
    if (!vars) return s;
    return String(s).replace(/\{(\w+)\}/g, function (_, k) {
      return vars[k] == null ? '' : String(vars[k]);
    });
  }

  function t(zh, vars) {
    var s = lang === 'en' ? (EN[zh] || zh) : zh;
    return interpolate(s, vars);
  }

  function setLang(next) {
    lang = next === 'en' ? 'en' : 'zh';
    try { localStorage.setItem(KEY, lang); } catch (e) { /* ignore */ }
    apply();
    return lang;
  }

  function apply(root) {
    var doc = typeof document !== 'undefined' ? document : null;
    if (!doc) return;
    if (doc.documentElement) doc.documentElement.lang = htmlLang[lang] || lang;
    var scope = root || doc;
    scope.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (!key) return;
      if (el.childElementCount && el.querySelector('kbd, span.nav-icon')) {
        var textNode = Array.prototype.find.call(el.childNodes, function (n) { return n.nodeType === 3 && n.textContent.trim(); });
        if (textNode) textNode.textContent = t(key);
        else {
          var label = el.querySelector('[data-i18n-label]');
          if (label) label.textContent = t(key);
        }
      } else {
        el.textContent = t(key);
      }
    });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
    });
    scope.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
      el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
    });
    scope.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });
    var sel = doc.getElementById('lang-select');
    if (sel && sel.value !== lang) sel.value = lang;
  }

  var api = {
    t: t,
    setLang: setLang,
    apply: apply,
    get lang() { return lang; },
    locale: function () { return htmlLang[lang] || lang; },
    keys: function () { return Object.keys(EN); },
    en: EN,
  };

  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  root.TestHubI18n = api;
